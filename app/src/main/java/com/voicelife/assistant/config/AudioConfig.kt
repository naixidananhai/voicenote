package com.voicelife.assistant.config

/**
 * 音频处理统一配置文件
 * 
 * 包含VAD（语音活动检测）和Whisper（语音识别）的所有可调参数
 * 修改这些参数可以优化检测效果和转录性能
 * 
 * 使用方法：
 * 1. 调整VAD参数减少误检测（环境音被误认为人声）
 * 2. 调整Whisper参数提高转录速度和准确性
 */
object AudioConfig {
    
    // ==================== VAD 语音活动检测参数 ====================
    
    object VAD {
        /**
         * 人声概率阈值
         * 范围: 0.0 ~ 1.0
         * 
         * 说明: VAD模型输出的概率超过此阈值才认为是人声
         * - 值越低: 越灵敏，容易误检测环境音为人声
         * - 值越高: 越严格，可能漏检轻声说话
         * 
         * 建议:
         * - 安静环境: 0.3 ~ 0.4
         * - 嘈杂环境: 0.5 ~ 0.7
         * - 当前问题"太多环境音": 建议提高到 0.5 或 0.6
         */
        const val VOICE_THRESHOLD = 0.5f  // 原值0.3，提高以减少误检测
        
        /**
         * 触发录音所需的连续人声帧数
         * 单位: 帧 (每帧约32ms)
         * 
         * 说明: 连续检测到N帧人声才开始录音，防止瞬间噪音触发
         * - 值越小: 响应越快，但容易被短暂噪音触发
         * - 值越大: 需要更长时间的持续人声才开始录音
         * 
         * 建议:
         * - 快速响应: 2 ~ 3 帧 (约64~96ms)
         * - 稳定检测: 5 ~ 8 帧 (约160~256ms)
         * - 当前问题"太多环境音": 建议提高到 5 或 6
         */
        const val MIN_VOICE_FRAMES = 5  // 原值3，提高以减少误触发
        
        /**
         * 结束录音所需的连续静音帧数
         * 单位: 帧 (每帧约32ms)
         * 
         * 说明: 连续N帧静音才结束当前录音
         * - 值越小: 说话停顿时容易断开录音
         * - 值越大: 可以容忍更长的停顿，录音更完整
         * 
         * 建议:
         * - 快速响应: 20 ~ 30 帧 (约0.6~1秒)
         * - 完整录音: 40 ~ 60 帧 (约1.3~2秒)
         */
        const val MIN_SILENCE_FRAMES = 45  // 原值30，约1.5秒静音才结束
        
        /**
         * 音频采样率
         * 单位: Hz
         * 
         * 说明: Silero VAD模型要求16kHz
         * 警告: 不要修改此值，否则VAD模型无法正常工作
         */
        const val SAMPLE_RATE = 16000
        
        /**
         * 每帧采样数
         * 单位: 采样点
         * 
         * 说明: Silero VAD模型要求512采样点/帧
         * 每帧时长 = 512 / 16000 = 32ms
         * 警告: 不要修改此值，否则VAD模型无法正常工作
         */
        const val FRAME_SIZE = 512
        
        /**
         * 能量阈值（可选的额外过滤）
         * 范围: 0.0 ~ 1.0
         * 
         * 说明: 音频帧的RMS能量低于此值时直接判定为静音
         * 可以在VAD之前快速过滤掉低能量噪音
         * - 0.0: 禁用能量过滤
         * - 0.01 ~ 0.05: 过滤极低能量噪音
         */
        const val ENERGY_THRESHOLD = 0.02f
        
        /**
         * 是否启用能量预过滤
         * 
         * 说明: 启用后，低能量音频帧不会送入VAD模型
         * 可以减少CPU使用，但可能漏检轻声说话
         */
        const val ENABLE_ENERGY_FILTER = true
    }
    
    // ==================== 录音会话参数 ====================
    
    object Recording {
        /**
         * 最小录音时长
         * 单位: 毫秒
         * 
         * 说明: 录音时长小于此值的文件会被丢弃
         * 用于过滤太短的误触发录音
         * 
         * 建议:
         * - 1000 ~ 2000ms: 过滤1-2秒以下的短录音
         */
        const val MIN_DURATION_MS = 1500L  // 1.5秒以下的录音丢弃
        
        /**
         * 最大录音时长
         * 单位: 毫秒
         * 
         * 说明: 单次录音的最大时长，超过后自动分割
         * 防止单个文件过大
         * 
         * 建议:
         * - 300000ms (5分钟): 适合一般对话
         * - 600000ms (10分钟): 适合长时间讲话
         */
        const val MAX_DURATION_MS = 300000L  // 5分钟
        
        /**
         * 预缓冲时长
         * 单位: 毫秒
         * 
         * 说明: 检测到人声前保留的音频时长
         * 确保录音开头不会被截断
         * 
         * 建议: 500 ~ 1000ms
         */
        const val PRE_BUFFER_MS = 800L
        
        /**
         * 智能合并间隔
         * 单位: 毫秒
         * 
         * 说明: 两段人声间隔小于此值时合并为一段录音
         * 避免说话停顿导致录音被分割
         * 
         * 建议: 2000 ~ 5000ms
         */
        const val MERGE_INTERVAL_MS = 3000L
    }
    
    // ==================== Whisper 语音识别参数 ====================
    
    object Whisper {
        /**
         * 语言设置
         * 
         * 可选值:
         * - "auto": 自动检测语言（推荐，支持中英文混合）
         * - "zh": 强制中文
         * - "en": 强制英文
         * - "ja": 日文
         * - 其他语言代码...
         * 
         * 说明: 指定语言可以提高识别速度和准确性
         * 但如果说的是其他语言会导致识别错误
         */
        const val LANGUAGE = "auto"
        
        /**
         * 是否翻译为英文
         * 
         * 说明: 
         * - false: 保持原语言输出
         * - true: 将所有语言翻译为英文
         */
        const val TRANSLATE = false
        
        /**
         * 使用的线程数
         * 
         * 说明: Whisper推理使用的CPU线程数
         * - 值越大: 转录越快，但CPU占用越高
         * - 值越小: 转录越慢，但省电
         * 
         * 建议:
         * - 高性能手机: 4 ~ 6
         * - 普通手机: 2 ~ 4
         * - 省电模式: 1 ~ 2
         * 
         * 当前问题"转录太慢": 可以尝试增加到 4 或 6
         */
        const val NUM_THREADS = 4  // 原值可能是2，增加以提高速度
        
        /**
         * 是否使用GPU加速
         * 
         * 说明: 部分设备支持GPU加速Whisper推理
         * 警告: 不是所有设备都支持，可能导致崩溃
         */
        const val USE_GPU = false
        
        /**
         * 最大解码长度
         * 单位: token数
         * 
         * 说明: 单次推理的最大输出长度
         * 较长的音频可能需要更大的值
         */
        const val MAX_LEN = 0  // 0表示自动
        
        /**
         * 是否输出时间戳
         * 
         * 说明: 是否在转录结果中包含时间戳
         */
        const val TIMESTAMPS = false
        
        /**
         * 音频上下文大小
         * 单位: 秒
         * 
         * 说明: Whisper处理的音频窗口大小
         * 默认30秒是Whisper的标准设置
         */
        const val AUDIO_CTX = 0  // 0表示使用默认值(30秒)
        
        /**
         * 初始提示词
         * 
         * 说明: 给Whisper的初始提示，可以提高特定领域的识别准确性
         * 例如: "以下是普通话对话。" 可以提高中文识别
         */
        const val INITIAL_PROMPT = ""
        
        /**
         * 波束搜索大小
         * 
         * 说明: 解码时的搜索宽度
         * - 值越大: 结果越准确，但速度越慢
         * - 值越小: 速度越快，但可能不够准确
         * 
         * 建议:
         * - 追求速度: 1 ~ 2
         * - 追求准确: 5
         */
        const val BEAM_SIZE = 2  // 减小以提高速度
        
        /**
         * 最佳候选数
         * 
         * 说明: 保留的最佳解码候选数量
         */
        const val BEST_OF = 1  // 减小以提高速度
    }
    
    // ==================== 存储管理参数 ====================
    
    object Storage {
        /**
         * 录音文件保留天数
         * 单位: 天
         * 
         * 说明: 已转录的录音文件保留多少天后自动删除
         */
        const val RETENTION_DAYS = 7
        
        /**
         * 最小可用空间
         * 单位: MB
         * 
         * 说明: 可用空间低于此值时触发清理
         */
        const val MIN_FREE_SPACE_MB = 500L
        
        /**
         * 单个录音文件最大大小
         * 单位: MB
         * 
         * 说明: 超过此大小的录音会被分割
         */
        const val MAX_FILE_SIZE_MB = 50L
    }
    
    // ==================== 调试参数 ====================
    
    object Debug {
        /**
         * 是否启用详细日志
         */
        const val VERBOSE_LOGGING = true
        
        /**
         * VAD概率日志间隔
         * 单位: 帧
         * 
         * 说明: 每隔N帧输出一次VAD概率日志
         */
        const val VAD_LOG_INTERVAL = 50
        
        /**
         * 音频数据日志间隔
         * 单位: 帧
         */
        const val AUDIO_LOG_INTERVAL = 100
    }
}
